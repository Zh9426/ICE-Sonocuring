function summary=verify_curing_only()
%VERIFY_CURING_ONLY Offline regression, four minimal drivers, Code Analyzer.
root=fileparts(fileparts(mfilename('fullpath')));
addpath(fullfile(root,'verasonics','dual_mode'));
addpath(fullfile(root,'verasonics','curing_mode'));
out=fullfile(root,'results','curing_only_2026-11-03');
if ~isfolder(out), mkdir(out); end
tests=dir(fullfile(root,'tests','test_verasonics_*.m'));
testPaths=arrayfun(@(v)fullfile(v.folder,v.name),tests,'UniformOutput',false);
assert(~isempty(testPaths),'No Verasonics tests found.');
testLog=evalc('testResults=runtests(testPaths);');
writeText(fullfile(out,'tests.log'),testLog);
writetable(table(testResults),fullfile(out,'test_results.csv'));
fprintf('TESTS total=%d passed=%d failed=%d incomplete=%d\n',numel(testResults), ...
    sum([testResults.Passed]),sum([testResults.Failed]),sum([testResults.Incomplete]));
assertSuccess(testResults);
groups=icec.variants(); cfg=icec.default_config(root);
rows=struct('variant',{},'entry',{},'active_elements',{},'first_rank',{},'last_rank',{}, ...
    'aperture_width_mm',{},'frequency_mhz',{},'cycles',{},'pri_us',{},'groups',{}, ...
    'pulses_per_group',{},'total_pulses',{},'nominal_on_time_us',{}, ...
    'total_element_on_time_us',{},'events',{},'startup_hv_omitted',{}, ...
    'effective_default_supply_request_v',{},'mat_path',{});
for k=1:numel(groups)
    [s,r,used]=feval(groups(k).entry,cfg,fullfile(out,'drivers'));
    assert(isequal(used.exposure,cfg.exposure),'Variants must retain the same exposure settings.');
    assert(all([s.Event.rcv]==0 & [s.Event.recon]==0 & [s.Event.process]==0));
    assert(~any(isfield(s,{'Receive','PData','Recon','Process','UI'})));
    assert(isscalar(s.TW) && all([s.TX.waveform]==1));
    assert(~any(strcmp({s.SeqControl.command},'transferToHost')));
    rows(k)=struct('variant',groups(k).name,'entry',groups(k).entry, ...
        'active_elements',r.partition.exposure_count,'first_rank',min(groups(k).ranks), ...
        'last_rank',max(groups(k).ranks),'aperture_width_mm',r.operating_envelope.exposure_aperture_width_mm, ...
        'frequency_mhz',used.exposure.frequency_mhz,'cycles',used.exposure.cycles, ...
        'pri_us',used.exposure.pri_us,'groups',used.sequence.num_groups, ...
        'pulses_per_group',used.exposure.pulses_per_focus, ...
        'total_pulses',r.timing.total_exposure_pulses, ...
        'nominal_on_time_us',r.operating_envelope.exposure_total_on_time_us, ...
        'total_element_on_time_us',r.operating_envelope.total_element_on_time_us, ...
        'events',numel(s.Event),'startup_hv_omitted',r.startup_hv_omitted, ...
        'effective_default_supply_request_v',icevs.requested_voltage(used.exposure), ...
        'mat_path',r.output_paths.mat);
end
summary=struct2table(rows);
writetable(summary,fullfile(out,'variant_summary.csv'),'Encoding','UTF-8');
codeFiles=[dir(fullfile(root,'verasonics','dual_mode','**','*.m')); ...
    dir(fullfile(root,'verasonics','curing_mode','**','*.m')); tests; ...
    dir(fullfile(root,'scripts','verify_verasonics_dual_mode.m')); ...
    dir(fullfile(root,'scripts','verify_shared_aperture.m')); ...
    dir(fullfile(root,'scripts','verify_curing_only.m'))];
analysis=struct('file',{},'messages',{});
for k=1:numel(codeFiles)
    file=fullfile(codeFiles(k).folder,codeFiles(k).name);
    analysis(k)=struct('file',file,'messages',checkcode(file,'-id'));
end
writeText(fullfile(out,'code_analysis.json'), ...
    jsonencode(struct('matlab_version',version,'files',analysis),'PrettyPrint',true));
fprintf('ANALYZER files=%d messages=%d\n',numel(analysis), ...
    sum(arrayfun(@(v)numel(v.messages),analysis)));
disp(summary(:,{'variant','active_elements','first_rank','last_rank', ...
    'aperture_width_mm','total_pulses','events'}));
end
function writeText(file,content)
fid=fopen(file,'w','n','UTF-8');
if fid<0, error('icevs:Export','Cannot write %s.',file); end
cleanup=onCleanup(@()fclose(fid));
fwrite(fid,unicode2native(content,'UTF-8'),'uint8');
end
