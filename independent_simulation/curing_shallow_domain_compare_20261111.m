function comparison=curing_shallow_domain_compare_20261111(variant)
%CURING_SHALLOW_DOMAIN_COMPARE_20261111 Same-grid full vs reduced-z domain.
root=fileparts(mfilename('fullpath')); base=fullfile(root,'results','curing_field_2026-11-10');
f=load(fullfile(base,'bli_gpu_full',[lower(variant) '_dx52_field.mat']), ...
    'p_amp','qp','x_m','y_m','z_m','dt_s','Nt');
s=load(fullfile(base,'bli_gpu_shallow',[lower(variant) '_dx52_field.mat']), ...
    'p_amp','qp','x_m','y_m','z_m','dt_s','Nt');
out=fullfile(base,'bli_gpu_shallow',[lower(variant) '_dx52_domain_comparison.csv']);
assert(~isfile(out),'iceind:NoOverwrite','Comparison output exists.');
zfull=f.z_m(:); zshort=s.z_m(:);
assert(numel(f.x_m)==numel(s.x_m) && numel(f.y_m)==numel(s.y_m) && ...
    max(abs(f.x_m(:)-s.x_m(:)))<1e-12 && max(abs(f.y_m(:)-s.y_m(:)))<1e-12 && ...
    max(abs(zfull(1:numel(zshort))-zshort))<1e-12 && ...
    abs(f.dt_s-s.dt_s)<1e-18 && f.Nt==s.Nt,'iceind:Shallow','Grid/time mismatch.');
z=s.z_m(:); names={'z0_source_plane';'z_gt0_to_0p26';'z_0p26_to_0p52'; ...
    'z_0p52_to_1';'z_1_to_2';'z_2_to_4';'z_0_to_2'};
masks={abs(z)<1e-12,z>1e-12 & z<.26e-3-1e-12, ...
    z>=.26e-3-1e-12 & z<.52e-3-1e-12,z>=.52e-3-1e-12 & z<1e-3-1e-12, ...
    z>=1e-3-1e-12 & z<2e-3-1e-12,z>=2e-3-1e-12 & z<4e-3-1e-12, ...
    z>=-1e-12 & z<2e-3-1e-12};
pl2=nan(7,1); ql2=pl2; pmaxChange=pl2; qmaxChange=pl2;
for k=1:numel(masks)
    zi=find(masks{k}); a=double(f.p_amp(:,:,zi)); b=double(s.p_amp(:,:,zi));
    c=double(f.qp(:,:,zi)); d=double(s.qp(:,:,zi));
    pl2(k)=norm(a(:)-b(:))/norm(a(:)); ql2(k)=norm(c(:)-d(:))/norm(c(:));
    pmaxChange(k)=max(b(:))/max(a(:))-1; qmaxChange(k)=max(d(:))/max(c(:))-1;
end
comparison=table(names,pl2,ql2,pmaxChange,qmaxChange,'VariableNames', ...
    {'region','pressure_l2_relative_full','qp_l2_relative_full', ...
    'pressure_peak_change_relative_full','qp_peak_change_relative_full'});
writetable(comparison,out); disp(comparison);
end
