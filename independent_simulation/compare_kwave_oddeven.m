function r=compare_kwave_oddeven()
%COMPARE_KWAVE_ODDEVEN Fixed-coordinate comparison of unnormalised 3D fields.
c=iceind.kwave_focus_config(); out=c.output_dir;
a=load(fullfile(out,'even32_focus20mm_dx65um.mat'),'p_peak_pa','x_m','y_m','z_m','report');
b=load(fullfile(out,'even32_focus20mm_dx52um.mat'),'p_peak_pa','x_m','y_m','z_m','report');
% Common forward ROI excluding source layer and a boundary margin.
x=(-4:.13:4)*1e-3; y=(-2:.13:2)*1e-3; z=(2:.13:29)*1e-3;
[xx,yy,zz]=ndgrid(x,y,z);
pa=interpn(a.x_m,a.y_m,a.z_m,double(a.p_peak_pa),xx,yy,zz,'linear');
pb=interpn(b.x_m,b.y_m,b.z_m,double(b.p_peak_pa),xx,yy,zz,'linear');
assert(all(isfinite(pa),'all') && all(isfinite(pb),'all'),'iceind:Comparison','Comparison ROI outside grid.');
l2=norm(pa(:)-pb(:))/norm(pb(:));
peakChange=abs(a.report.metrics.forward_peak_pa_assumed/b.report.metrics.forward_peak_pa_assumed-1);
positionChange=norm(a.report.metrics.forward_peak_xyz_m-b.report.metrics.forward_peak_xyz_m);
r=struct('coarse_dx_m',65e-6,'fine_dx_m',52e-6,'common_roi_m',[-4 4;-2 2;2 29]*1e-3, ...
    'relative_l2_3d',l2,'relative_peak_pressure_change',peakChange, ...
    'peak_position_change_m',positionChange,'proposed_l2_threshold',.05, ...
    'proposed_position_change_threshold_m',.13e-3, ...
    'two_grid_check_passed',l2<=.05 && peakChange<=.05 && positionChange<=.13e-3, ...
    'full_convergence','not_established_two_grids_only', ...
    'domain_pml_sensitivity','not_tested','physical_validation','unknown');
fid=fopen(fullfile(out,'grid_comparison.json'),'w','n','UTF-8'); cleanup=onCleanup(@()fclose(fid));
fwrite(fid,jsonencode(r,'PrettyPrint',true),'char');
t=table([65;52],[a.report.metrics.forward_peak_error_m;b.report.metrics.forward_peak_error_m]*1e3, ...
    [a.report.metrics.forward_peak_xyz_m;b.report.metrics.forward_peak_xyz_m]*1e3, ...
    [a.report.metrics.target_over_forward_peak;b.report.metrics.target_over_forward_peak], ...
    [a.report.runtime_s;b.report.runtime_s], ...
    'VariableNames',{'dx_um','peak_error_mm','peak_xyz_mm','target_over_peak','runtime_s'});
writetable(t,fullfile(out,'focus_summary.csv')); disp(t); disp(r);
end
