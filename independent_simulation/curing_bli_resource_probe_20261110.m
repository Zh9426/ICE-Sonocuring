function result=curing_bli_resource_probe_20261110(variant,dx_um)
%CURING_BLI_RESOURCE_PROBE Actual driver source, 16 time steps only.
% This is a resource and compatibility test, not a physical field result.
root=fileparts(mfilename('fullpath')); old=path; cleanup=onCleanup(@()path(old));
addpath(root,fullfile(root,'dependencies','k-wave-1.4.1','k-Wave'));
assert(ismember(dx_um,[65 52]) && ismember(string(variant),["All64","Center16"]), ...
    'iceind:CuringField','Only the first-stage variants and grids are supported.');
cases=iceind.curing_field_cases(); idx=find(strcmp({cases.variant},variant) & ...
    abs([cases.dx_m]-dx_um*1e-6)<1e-12,1);
assert(~isempty(idx),'iceind:CuringField','No matching case.'); c=cases(idx);
driverNames=struct('All64','ICE_CuringOnly_ExposureFFFFFFFFFFFFFFFF_exposure_only.mat', ...
    'Center16','ICE_CuringOnly_Exposure000000FFFF000000_exposure_only.mat');
driver=fullfile(root,'results','curing_export_2026-11-10',driverNames.(variant));
out=fullfile(root,'results','curing_field_2026-11-10', ...
    sprintf('bli_resource_%s_dx%d',lower(variant),dx_um));
assert(~isfolder(out),'iceind:NoOverwrite','Resource output already exists.'); mkdir(out);
p=System.Diagnostics.Process.GetCurrentProcess(); p.Refresh(); baseline=double(p.WorkingSet64);
t=tic; [g,medium,source,sensor,meta]=iceind.curing_bli_prepare(c,driver); prepare_s=toc(t);
steps=16; g.setTime(steps,g.dt); source.p=source.p(:,1:steps);
sensor.record={'p_max_all','p_min_all','p_rms','p_final'}; sensor.record_start_index=1;
t=tic; data=kspaceFirstOrder3D(g,medium,source,sensor,'PMLInside',false, ...
    'PMLSize',meta.pml_cells,'PlotSim',false,'DataCast','single'); elapsed=toc(t);
p.Refresh(); endWorking=double(p.WorkingSet64); lifetimePeak=double(p.PeakWorkingSet64);
assert(numel(data.p_rms)==prod(meta.grid_size) && all(isfinite(data.p_rms)), ...
    'iceind:CuringBLIResource','Unexpected RMS data.');
result=struct('purpose','16-step CPU resource test; no propagation outcome or physical field', ...
    'variant',variant,'dx_um',dx_um,'grid',meta.grid_size,'pml_cells',meta.pml_cells, ...
    'dt_s',g.dt,'steps',steps,'prepare_s',prepare_s,'runtime_s',elapsed, ...
    'source_points',nnz(source.p_mask),'record',{sensor.record}, ...
    'baseline_working_set_bytes',baseline,'end_working_set_bytes',endWorking, ...
    'lifetime_peak_working_set_bytes',lifetimePeak, ...
    'memory_note','lifetime peak cannot be attributed to this solve', ...
    'matlab',version,'generated_local',datestr(now,30));
iceind.curing_field_write_json(fullfile(out,'resource.json'),result);
disp(result);
end
