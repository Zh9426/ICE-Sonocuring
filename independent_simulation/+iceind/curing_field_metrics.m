function m=curing_field_metrics(p_amp,x,y,z,target,dx)
%CURING_FIELD_METRICS Peak-amplitude field metrics with an explicit -6 dB cut.
% p_amp(x,y,z)=max_t|p| from p_max_all/p_min_all under the assumed source.
% z is measured forward from the source plane (m). The forward analysis ROI is
% z>=2 mm, which excludes the source plane and the first 2 mm of near field.
% The -6 dB pressure-amplitude ratio is 10^(-6/20). Pressure-squared
% intensity has the same decibel ratio (10*log10 of the squared ratio).
assert(isreal(p_amp) && all(isfinite(p_amp),'all') && all(p_amp(:)>=0), ...
    'iceind:CuringField','Expected a finite nonnegative peak-amplitude volume.');
target=target(:)'; hx=2e-3; hy=2e-3; hz=4e-3; % explicit target box halfwidths
nx=numel(x); ny=numel(y); nz=numel(z);
assert(isequal(size(p_amp),[nx ny nz]),'iceind:CuringField','Axis/volume size mismatch.');
fwd=find(z>=2e-3); assert(~isempty(fwd),'iceind:CuringField','Empty forward ROI.');
sub=p_amp(:,:,fwd);
[pk,lin]=max(sub(:)); [a,b,cc]=ind2sub(size(sub),lin); c=fwd(cc);
assert(pk>0,'iceind:CuringField','Forward ROI has zero amplitude; peak and widths are undefined.');
peak_xyz=[x(a) y(b) z(c)];
peak_on_boundary=a==1 || a==nx || b==1 || b==ny || c==fwd(1) || c==fwd(end);
ratio=10^(-6/20); thr=ratio*pk;
[w6x,cx]=width(x,double(p_amp(:,b,c)),a);
[w6y,cy]=width(y,double(p_amp(a,:,c)),b);
[w6z,cz]=width(z(fwd),double(p_amp(a,b,fwd)),find(fwd==c));
region=sub>=thr;
region_clipped=peak_on_boundary || any(region(1,:,:),'all') || any(region(end,:,:),'all') || ...
    any(region(:,1,:),'all') || any(region(:,end,:),'all') || ...
    any(region(:,:,1),'all') || any(region(:,:,end),'all');
ix=find(abs(x-target(1))<=hx+1e-12); iy=find(abs(y-target(2))<=hy+1e-12);
izb=find(abs(z-target(3))<=hz+1e-12);
assert(~isempty(ix) && ~isempty(iy) && ~isempty(izb),'iceind:CuringField','Empty target box.');
% Translate target z range into forward-subset indices.
zmask=ismember(fwd,izb);
intarget=false(size(sub));
intarget(ix,iy,zmask)=true;
targetIndices=find(intarget);
assert(~isempty(targetIndices),'iceind:CuringField','Target box does not intersect forward ROI.');
[targetPeak,idx]=max(sub(targetIndices)); targetIdx=targetIndices(idx);
[ta,tb,tc]=ind2sub(size(sub),targetIdx); tc=fwd(tc);
if targetPeak>0
    [twx,tcx]=width(x,double(p_amp(:,tb,tc)),ta);
    [twy,tcy]=width(y,double(p_amp(ta,:,tc)),tb);
    [twz,tcz]=width(z,double(squeeze(p_amp(ta,tb,:))),tc);
else
    twx=NaN; twy=NaN; twz=NaN; tcx=true; tcy=true; tcz=true;
end
[~,ti]=min(abs(x-target(1))); [~,tj]=min(abs(y-target(2))); [~,tk]=min(abs(z-target(3)));
outsideIndices=find(~intarget);
assert(~isempty(outsideIndices),'iceind:CuringField','Empty outside-target ROI.');
[outsideMax,idx]=max(sub(outsideIndices)); outsideIdx=outsideIndices(idx);
[oa,ob,oc]=ind2sub(size(sub),outsideIdx); oc=fwd(oc);
targetXYZ=[x(ta) y(tb) z(tc)]; targetError=norm(targetXYZ-target);
outsideXYZ=[x(oa) y(ob) z(oc)];
if targetPeak==0
    targetXYZ=[NaN NaN NaN]; targetError=NaN; pointRatio=NaN; outsideRatio=NaN;
else
    pointRatio=double(p_amp(ti,tj,tk))/double(targetPeak);
    outsideRatio=double(outsideMax)/double(targetPeak);
end
if outsideMax==0, outsideXYZ=[NaN NaN NaN]; end
zplane=min(abs(z-target(3))); iz=find(abs(z-target(3))==zplane,1);
plane=p_amp(:,:,iz); [planePeak,lin2]=max(plane(:)); [pa,pb]=ind2sub(size(plane),lin2);
shallow1=p_amp(:,:,z>=0 & z<2e-3);
shallow2=p_amp(:,:,z>=2e-3 & z<5e-3);
ax=min(abs(x)); ay=min(abs(y)); ia=find(abs(x)==ax,1); ib=find(abs(y)==ay,1);
axisProfile=double(p_amp(ia,ib,:)); [axisPeak,iaxis]=max(axisProfile);
beyond=z>target(3)+hz;
lateralOut=abs(x(:))>target(1)+hx | abs(y(:)')>target(2)+hy;
latSub=reshape(sub,nx*ny,[]); latSub=latSub(lateralOut(:),:);
m=struct('forward_roi_z_min_m',2e-3, ...
    'forward_peak_pa_assumed',double(pk), ...
    'forward_peak_error_to_target_m',norm(peak_xyz-target), ...
    'forward_peak_on_boundary',peak_on_boundary, ...
    'six_db_threshold_pa',double(thr),'six_db_threshold_db',-6, ...
    'six_db_definition',['pressure amplitude >= 10^(-6/20)*forward_peak (-6 dB); ' ...
        'pressure-squared intensity ratio is also -6 dB'], ...
    'six_db_volume_m3',nnz(region)*dx^3, ...
    'six_db_fraction_of_forward_volume',nnz(region)/numel(sub), ...
    'six_db_fraction_inside_target_box',nnz(region & intarget)/max(nnz(region),1), ...
    'six_db_region_touches_forward_boundary',region_clipped, ...
    'target_box_peak_pa_assumed',double(targetPeak), ...
    'target_peak_is_zero',targetPeak==0, ...
    'target_peak_xyz_m',targetXYZ, ...
    'target_peak_error_to_target_m',targetError, ...
    'target_peak_on_box_boundary',any([ta==ix(1),ta==ix(end),tb==iy(1),tb==iy(end),tc==izb(1),tc==izb(end)]), ...
    'target_peak_widths_m',[twx twy twz], ...
    'target_peak_width_clipped',[tcx tcy tcz], ...
    'target_point_nearest_xyz_m',[x(ti) y(tj) z(tk)], ...
    'target_point_peak_pa_assumed',double(p_amp(ti,tj,tk)), ...
    'target_point_over_target_peak',pointRatio, ...
    'target_over_forward_peak',double(targetPeak)/double(pk), ...
    'outside_target_box_peak_pa_assumed',double(outsideMax), ...
    'outside_peak_is_zero',outsideMax==0, ...
    'outside_target_peak_xyz_m',outsideXYZ, ...
    'outside_over_target_peak',outsideRatio, ...
    'target_plane_sampled_z_m',z(iz),'target_plane_peak_pa_assumed',double(planePeak), ...
    'target_plane_lateral_error_m',norm([x(pa) y(pb)]-target(1:2)), ...
    'target_plane_peak_over_forward_peak',double(planePeak)/double(pk), ...
    'shallow_0_2mm_peak_pa_assumed',double(max(shallow1,[],'all')), ...
    'shallow_0_2mm_over_forward_peak',double(max(shallow1,[],'all'))/double(pk), ...
    'shallow_2_5mm_peak_pa_assumed',double(max(shallow2,[],'all')), ...
    'shallow_2_5mm_over_forward_peak',double(max(shallow2,[],'all'))/double(pk), ...
    'beyond_target_box_peak_pa_assumed',double(max(p_amp(:,:,beyond),[],'all')), ...
    'beyond_target_over_forward_peak',double(max(p_amp(:,:,beyond),[],'all'))/double(pk), ...
    'lateral_outside_target_peak_pa_assumed',double(max(latSub(:))), ...
    'lateral_outside_over_forward_peak',double(max(latSub(:)))/double(pk), ...
    'axis_peak_pa_assumed',double(axisPeak),'axis_peak_z_m',z(iaxis), ...
    'width_definition','contiguous -6 dB amplitude crossings through the forward peak; interpolated; NaN if unclosed', ...
    'pressure_definition','per-voxel max_t(abs(p)) from p_max_all/p_min_all; not a simultaneous snapshot', ...
    'units','pressure Pa under the assumed 1 Pa reference source; widths m; volumes m^3', ...
    'provenance','synthetic_assumed_lossless_flat_source_no_cure_no_safety_threshold', ...
    'not_acoustic_energy','Peak pressure and volumes above threshold are not deposited energy, dose, heating or cure.');
m.forward_peak_xyz_m=peak_xyz;
m.six_db_widths_m=[w6x w6y w6z];
m.six_db_width_clipped=[cx cy cz];
m.target_m=target;
m.target_halfwidth_m=[hx hy hz];
m.target_plane_peak_xy_m=[x(pa) y(pb)];
end
function [w,clipped]=width(axis,values,ip)
values=double(values(:)); threshold=values(ip)*10^(-6/20);
lo=ip; hi=ip;
while lo>1 && values(lo)>=threshold, lo=lo-1; end
while hi<numel(values) && values(hi)>=threshold, hi=hi+1; end
clipped=values(lo)>=threshold || values(hi)>=threshold;
if clipped, w=NaN; return; end
xl=axis(lo)+(axis(lo+1)-axis(lo))*(threshold-values(lo))/(values(lo+1)-values(lo));
xh=axis(hi-1)+(axis(hi)-axis(hi-1))*(threshold-values(hi-1))/(values(hi)-values(hi-1));
w=xh-xl;
end
