function analysis=curing_field_compare(outdir)
%CURING_FIELD_COMPARE Cross-grid sensitivity at exact common physical points.
% 65 um and 52 um grids share every 260 um point, so no interpolation is used.
% Only completed cases are compared; a single completed case is reported as
% partial and never described as convergence.
if nargin<1 || isempty(outdir)
    root=fileparts(fileparts(mfilename('fullpath')));
    outdir=fullfile(root,'results','curing_field_2026-11-10');
end
if ~isfolder(outdir), mkdir(outdir); end
cases=iceind.curing_field_cases();
rows=struct('tag',{},'variant',{},'dx_m',{},'forward_peak_pa',{}, ...
    'forward_peak_z_mm',{},'target_peak_pa',{},'target_over_forward',{}, ...
    'shallow_0_2_over_forward',{},'shallow_2_5_over_forward',{}, ...
    'outside_over_target',{},'six_db_wx_mm',{},'six_db_wy_mm',{}, ...
    'six_db_wz_mm',{},'six_db_fraction_in_target',{},'axis_peak_z_mm',{});
done=false(1,numel(cases));
for k=1:numel(cases)
    f=fullfile(outdir,[cases(k).tag '_metrics.json']);
    if ~isfile(f), continue; end
    r=jsondecode(fileread(f)); m=r.metrics; done(k)=true;
    rows(end+1)=struct('tag',cases(k).tag,'variant',cases(k).variant, ...
        'dx_m',cases(k).dx_m,'forward_peak_pa',m.forward_peak_pa_assumed, ...
        'forward_peak_z_mm',m.forward_peak_xyz_m(3)*1e3, ...
        'target_peak_pa',m.target_box_peak_pa_assumed, ...
        'target_over_forward',m.target_over_forward_peak, ...
        'shallow_0_2_over_forward',m.shallow_0_2mm_over_forward_peak, ...
        'shallow_2_5_over_forward',m.shallow_2_5mm_over_forward_peak, ...
        'outside_over_target',m.outside_over_target_peak, ...
        'six_db_wx_mm',m.six_db_widths_m(1)*1e3, ...
        'six_db_wy_mm',m.six_db_widths_m(2)*1e3, ...
        'six_db_wz_mm',m.six_db_widths_m(3)*1e3, ...
        'six_db_fraction_in_target',m.six_db_fraction_inside_target_box, ...
        'axis_peak_z_mm',m.axis_peak_z_m*1e3); %#ok<AGROW>
end
pairs=struct('variant',{},'l2_forward',{},'l2_shallow_0_2',{}, ...
    'l2_shallow_2_5',{},'l2_5_20',{},'l2_target_box',{}, ...
    'l2_outside_target',{},'l2_beyond_24',{},'peak_shift_65_to_52_m',{}, ...
    'peak_amplitude_change_ratio',{});
variants=unique({cases.variant});
for vi=1:numel(variants)
    a=cases(find(strcmp({cases.variant},variants{vi}) & [cases.dx_m]==65e-6,1));
    b=cases(find(strcmp({cases.variant},variants{vi}) & [cases.dx_m]==52e-6,1));
    ia=find(strcmp({cases.tag},a.tag)); ib=find(strcmp({cases.tag},b.tag));
    if ~done(ia) || ~done(ib), continue; end
    A=load(fullfile(outdir,[a.tag '_field.mat']),'p_amp','x_m','y_m','z_m');
    B=load(fullfile(outdir,[b.tag '_field.mat']),'p_amp');
    pa=A.p_amp(1:4:end,1:4:end,1:4:end);
    pb=B.p_amp(1:5:end,1:5:end,1:5:end);
    assert(isequal(size(pa),size(pb)),'iceind:CuringField','Common-grid size mismatch.');
    xg=A.x_m(1:4:end); yg=A.y_m(1:4:end); zg=A.z_m(1:4:end);
    f=double(pa(:)); g=double(pb(:));
    [X,Y,Z]=ndgrid(xg,yg,zg);
    fullmask=Z>=2e-3;
    inT=abs(X)<=2e-3 & abs(Y)<=2e-3 & abs(Z-20e-3)<=4e-3;
    band=@(lo,hi) Z>=lo & Z<hi;
    rel=@(mask) norm(f(mask(:))-g(mask(:)))/max(norm(f(mask(:))),eps);
    ma=jsondecode(fileread(fullfile(outdir,[a.tag '_metrics.json']))).metrics;
    mb=jsondecode(fileread(fullfile(outdir,[b.tag '_metrics.json']))).metrics;
    pairs(end+1)=struct('variant',a.variant, ...
        'l2_forward',rel(fullmask), ...
        'l2_shallow_0_2',rel(band(0,2e-3)), ...
        'l2_shallow_2_5',rel(band(2e-3,5e-3)), ...
        'l2_5_20',rel(band(5e-3,20e-3)), ...
        'l2_target_box',rel(inT), ...
        'l2_outside_target',rel(~inT & fullmask), ...
        'l2_beyond_24',rel(band(24e-3,Inf)), ...
        'peak_shift_65_to_52_m',norm(ma.forward_peak_xyz_m-mb.forward_peak_xyz_m), ...
        'peak_amplitude_change_ratio',mb.forward_peak_pa_assumed/ma.forward_peak_pa_assumed); %#ok<AGROW>
end
analysis=struct('schema_version',1, ...
    'scope','cross-grid sensitivity at exact common points; no interpolation', ...
    'definitions',struct( ...
        'l2','||p65-p52||_2 / ||p65||_2 on every fourth 65 um and fifth 52 um sample (260 um common lattice)', ...
        'six_db','pressure amplitude 10^(-6/20)*forward peak; pressure-squared ratio also -6 dB', ...
        'bands','z measured forward from the source plane'), ...
    'limits',{{ ...
        'A two-grid comparison is not a convergence proof; source rasterization changes with dx.', ...
        'Peak-amplitude fields are not deposited energy, heating or cure.', ...
        'Only completed cases appear; missing cases are explicitly listed as not run.'}});
analysis.cases_completed={cases(done).tag};
analysis.rows=rows;
analysis.pairs=pairs;
iceind.curing_field_write_json(fullfile(outdir,'analysis.json'),analysis);
if ~isempty(rows), writetable(struct2table(rows),fullfile(outdir,'comparison.csv'),'Encoding','UTF-8'); end
fprintf('Compared %d cases; %d cross-grid pairs.\n',nnz(done),numel(pairs));
end
