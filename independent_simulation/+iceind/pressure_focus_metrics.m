function m=pressure_focus_metrics(p,x,y,z,target)
%PRESSURE_FOCUS_METRICS Quantify peak locations without assuming exact focus.
% p is max_t(abs(p)), in Pa under the assumed source. Coordinates are metres.
x=x(:); y=y(:); z=z(:);
assert(isequal(size(p),[numel(x) numel(y) numel(z)]) && all(isfinite(p),'all') && ...
    all(p>=0,'all'),'iceind:Field','Expected a finite nonnegative XYZ pressure volume.');
forward=find(z>=2e-3); % Excludes source plane and first 2 mm; explicit metric ROI.
near={find(abs(x-target(1))<=2e-3),find(abs(y-target(2))<=2e-3), ...
    find(abs(z-target(3))<=4e-3)};
assert(~isempty(forward) && all(~cellfun(@isempty,near)),'iceind:FocusROI','Empty analysis ROI.');
field=p(:,:,forward); [peak,ind]=max(field(:)); [a,b,c]=ind2sub(size(field),ind); c=forward(c);
xyz=[x(a) y(b) z(c)];
local=p(near{1},near{2},near{3}); [lp,ind]=max(local(:)); [la,lb,lc]=ind2sub(size(local),ind);
lxyz=[x(near{1}(la)) y(near{2}(lb)) z(near{3}(lc))];
[~,iz]=min(abs(z-target(3))); plane=p(:,:,iz); [pp,ind]=max(plane(:)); [pa,pb]=ind2sub(size(plane),ind);
[wx,cx]=width(x,p(:,b,c),a); [wy,cy]=width(y,p(a,:,c),b);
[wz,cz]=width(z(forward),p(a,b,forward),find(forward==c));
onBoundary=a==1 || a==numel(x) || b==1 || b==numel(y) || c==forward(1) || c==forward(end);
targetP=interpn(x,y,z,double(p),target(1),target(2),target(3),'linear');
m=struct('forward_roi_z_min_m',2e-3,'forward_peak_pa_assumed',double(peak), ...
    'forward_peak_xyz_m',xyz,'forward_peak_error_m',norm(xyz-target), ...
    'forward_peak_on_boundary',onBoundary, ...
    'near_target_halfwidth_m',[2 2 4]*1e-3,'near_target_peak_pa_assumed',double(lp), ...
    'near_target_peak_xyz_m',lxyz,'near_target_peak_error_m',norm(lxyz-target), ...
    'near_target_peak_on_boundary',la==1 || la==size(local,1) || lb==1 || lb==size(local,2) || lc==1 || lc==size(local,3), ...
    'target_pa_assumed_interpolated',targetP,'target_over_forward_peak',targetP/double(peak), ...
    'target_plane_sampled_z_m',z(iz),'target_plane_peak_xyz_m',[x(pa) y(pb) z(iz)], ...
    'target_plane_peak_pa_assumed',double(pp),'target_plane_lateral_error_m',norm([x(pa) y(pb)]-target(1:2)), ...
    'width_at_forward_peak_m',[wx wy wz],'width_clipped',[cx cy cz], ...
    'width_definition','Contiguous half-amplitude crossings through forward peak, approx -6.02 dB; NaN if unclosed.', ...
    'proposed_position_tolerance_m',.5e-3, ...
    'within_proposed_0p5mm_tolerance',~onBoundary && norm(xyz-target)<=.5e-3, ...
    'physical_accuracy','unknown','pressure_definition','max_t(abs(p)); not a simultaneous pressure snapshot');
end
function [w,clipped]=width(axis,values,ip)
values=double(values(:)); threshold=values(ip)/2;
lo=ip; hi=ip;
while lo>1 && values(lo)>=threshold, lo=lo-1; end
while hi<numel(values) && values(hi)>=threshold, hi=hi+1; end
clipped=values(lo)>=threshold || values(hi)>=threshold;
if clipped, w=NaN; return; end
xl=axis(lo)+(axis(lo+1)-axis(lo))*(threshold-values(lo))/(values(lo+1)-values(lo));
xh=axis(hi-1)+(axis(hi)-axis(hi-1))*(threshold-values(hi-1))/(values(hi)-values(hi-1));
w=xh-xl;
end
