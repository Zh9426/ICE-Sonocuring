function groups=curing_field_variants()
%CURING_FIELD_VARIANTS The four user entries for standalone pure illumination.
% Entry points live in verasonics/curing_mode and are only *called* to export
% their sequence MAT. No VSX, activation or hardware path is touched.
groups=struct( ...
    'name',{'All64','Center48','Center32','Center16'}, ...
    'ranks',{1:64,9:56,17:48,25:40}, ...
    'entry',{'SetUpICE_Curing_All64','SetUpICE_Curing_Center48', ...
             'SetUpICE_Curing_Center32','SetUpICE_Curing_Center16'}, ...
    'provenance','user_standalone_curing_entry_existing_code_unverified');
for k=1:numel(groups)
    groups(k).num_active=numel(groups(k).ranks);
    groups(k).variants_fixture='verasonics/curing_mode/+icec/variants.m';
end
end
