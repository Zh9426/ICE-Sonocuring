function m=pressure_exposure_metrics(qp,p,x,y,z,target,halfwidth,materialBounds)
%PRESSURE_EXPOSURE_METRICS Explicit assumed boxes and observed-volume proxies.
% Voxel centres inside closed boxes are counted, each with volume dx*dy*dz.
axes={x(:),y(:),z(:)}; n=cellfun(@numel,axes);
assert(isequal(size(qp),n) && isequal(size(p),n) && isreal(qp) && isreal(p) && ...
 all(isfinite(qp),'all') && all(qp>=0,'all') && all(isfinite(p),'all') && all(p>=0,'all'), ...
 'iceind:ExposureField','Expected nonnegative finite XYZ proxy/peak volumes.');
assert(isequal(size(materialBounds),[3 2]) && numel(target)==3 && numel(halfwidth)==3 && ...
 all(isfinite([materialBounds(:);target(:);halfwidth(:)])) && all(halfwidth>0) && ...
 all(materialBounds(:,2)>materialBounds(:,1)), ...
 'iceind:ExposureROI','Finite positive evaluation and target boxes required.');
target=target(:); halfwidth=halfwidth(:); bounds=[target-halfwidth,target+halfwidth];
steps=zeros(1,3); ids=cell(1,3); materialClipped=false; targetClipped=false;
for k=1:3
 d=diff(axes{k});
 assert(~isempty(d) && all(d>0) && max(abs(d-median(d)))<1e-12, ...
  'iceind:ExposureAxes','Uniform increasing SI axes required.');
 steps(k)=median(d);
 lo=axes{k}(1)-steps(k)/2; hi=axes{k}(end)+steps(k)/2;
 materialClipped=materialClipped || materialBounds(k,1)<lo-1e-12 || materialBounds(k,2)>hi+1e-12;
 targetClipped=targetClipped || bounds(k,1)<max(lo,materialBounds(k,1))-1e-12 || ...
  bounds(k,2)>min(hi,materialBounds(k,2))+1e-12;
 ids{k}=find(axes{k}>=materialBounds(k,1)-1e-12 & axes{k}<=materialBounds(k,2)+1e-12);
end
assert(all(~cellfun(@isempty,ids)),'iceind:ExposureROI','Empty observed material box.');
[xx,yy,zz]=ndgrid(axes{1}(ids{1}),axes{2}(ids{2}),axes{3}(ids{3}));
inside=abs(xx-target(1))<=halfwidth(1)+1e-12 & abs(yy-target(2))<=halfwidth(2)+1e-12 & ...
 abs(zz-target(3))<=halfwidth(3)+1e-12;
assert(any(inside,'all') && any(~inside,'all'),'iceind:ExposureROI','Empty target or outside region.');
q=double(qp(ids{1},ids{2},ids{3})); pp=double(p(ids{1},ids{2},ids{3}));
dv=prod(steps); targetMax=max(q(inside)); total=sum(q,'all')*dv; targetIntegral=sum(q(inside))*dv;
assert(targetMax>0 && total>0 && max(pp(inside))>0,'iceind:ExposureField', ...
 'Relative exposure metrics require an illuminated target and positive material integral.');
outside=q; outside(inside)=-Inf; [outsideMax,index]=max(outside(:));
before=zz<bounds(3,1)-1e-12; after=zz>bounds(3,2)+1e-12;
lateral=~inside & ~before & ~after;
m=struct('target_m',target','target_halfwidth_m_assumed',halfwidth', ...
 'material_bounds_m_assumed',materialBounds,'target_clipped',targetClipped, ...
 'material_clipped',materialClipped,'voxel_volume_m3',dv, ...
 'target_voxels',nnz(inside),'material_voxels',numel(q), ...
 'target_voxel_volume_m3',nnz(inside)*dv,'material_voxel_volume_m3',numel(q)*dv, ...
 'target_max_qp_pa2_s',targetMax,'target_min_qp_pa2_s',min(q(inside)), ...
 'target_mean_qp_pa2_s',mean(q(inside)),'target_cv_qp',std(q(inside),1)/mean(q(inside)), ...
 'target_qp_integral_pa2_s_m3',targetIntegral,'material_qp_integral_pa2_s_m3',total, ...
 'target_qp_fraction_of_material',targetIntegral/total, ...
 'outside_qp_fraction_of_material',(total-targetIntegral)/total, ...
 'outside_max_qp_pa2_s',outsideMax,'outside_over_target_max_qp',outsideMax/targetMax, ...
 'outside_max_xyz_m',[xx(index) yy(index) zz(index)], ...
 'outside_over_target_max_pressure',max(pp(~inside))/max(pp(inside)), ...
 'target_relative_halfmax_coverage',nnz(q(inside)>=.5*targetMax)/nnz(inside), ...
 'prefocal_qp_fraction_of_material',sum(q(before))*dv/total, ...
 'postfocal_qp_fraction_of_material',sum(q(after))*dv/total, ...
 'lateral_qp_fraction_of_material',sum(q(lateral))*dv/total, ...
 'units','Qp Pa^2 s; spatial integral Pa^2 s m^3; fractions are observed-volume proxy fractions, not energy.', ...
 'provenance','synthetic_target_assumed_material_box_no_cure_or_safety_threshold');
end
