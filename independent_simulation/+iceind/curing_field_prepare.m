function [kg,medium,source,sensor,m,wave]=curing_field_prepare(c,driverMat)
%CURING_FIELD_PREPARE Build a CPU k-Wave problem from one exported curing TX.
% Model: one assumed 1 Pa reference pressure signal per ACTIVE element, with
% the entry's own geometric focus delays. No per-element or cross-grid budget
% matching. Flat finite rectangles, no elevation lens, lossless fluid.
assert(isfile(driverMat),'iceind:CuringField','Missing driver MAT: %s',driverMat);
s=load(driverMat);
assert(isfield(s,'ICEConfig'),'iceind:CuringField','Driver MAT lacks ICEConfig.');
ranks=sort(double(s.ICEConfig.partition.exposure_ranks(:)'));
assert(isequal(ranks,sort(double(c.ranks(:)'))),'iceind:CuringField', ...
    'Driver rank mask does not match the requested case.');
b=iceind.compile_kwave(s);
assert(numel(b.tx)==1,'iceind:CuringField','Expected exactly one exposure TX.');
q=b.tx(1);
active=find(q.apod(:)~=0)';
assert(isequal(active,ranks),'iceind:CuringField', ...
    'TX apodization does not activate exactly the requested ranks.');
positions=b.geometry.positions_m;
width=b.geometry.width_m; height=b.geometry.height_m;
area=width*height;
n=round(c.domain_m/c.dx_m); pml=round(c.pml_m/c.dx_m);
assert(all(abs(n*c.dx_m-c.domain_m)<1e-12),'iceind:CuringField', ...
    'Grid spacing must divide the physical domain exactly.');
assert(abs(pml*c.dx_m-c.pml_m)<1e-12,'iceind:CuringField', ...
    'PML thickness must be an integer number of cells.');
kg=kWaveGrid(n(1),c.dx_m,n(2),c.dx_m,n(3),c.dx_m);
sourceZ=-c.domain_m(3)/2+c.source_offset_m;
[~,sourceIz]=min(abs(kg.z_vec-sourceZ));
assert(abs(kg.z_vec(sourceIz)-sourceZ)<1e-12,'iceind:CuringField', ...
    'Source plane must land on a grid plane.');
% Independent source-to-far-corner travel bound for the time window.
distance=sqrt((c.domain_m(1)/2+max(abs(positions(active,1))))^2 + ...
    (c.domain_m(2)/2+height/2)^2 + (c.domain_m(3)-c.source_offset_m)^2);
waveEnd=max(q.delay_s)+q.duration_s+2e-6;
kg.makeTime(b.sound_speed_m_s,c.cfl,waveEnd+distance/b.sound_speed_m_s+1e-6);
kg.setTime(max(kg.Nt,ceil(c.minimum_end_time_s/kg.dt)+1),kg.dt);
[wave,wm]=iceind.kw_waveform(q,kg.dt,waveEnd,c.source_amplitude_pa);
% Finite rectangular sources; exact area overlap in each direction.
[w,wx,wy]=iceind.curing_field_weights(kg.x_vec,kg.y_vec,c.dx_m,positions(active,:),width,height);
areaError=max(abs(sum(double(w),1)*c.dx_m^2-area));
assert(areaError<1e-12,'iceind:CuringField','Rectangular source was clipped.');
plane=any(w~=0,2);
source.p_mask=false(n);
source.p_mask(:,:,sourceIz)=reshape(plane,n(1),n(2));
source.p=w(plane,:)*wave(active,:);
source.p_mode='additive';
medium=struct('sound_speed',b.sound_speed_m_s,'density',c.density_kg_m3);
sensor.mask=true(n);
sensor.record={'p_max_all','p_min_all'};
target=double(s.ICEConfig.exposure.foci_mm(1,:))*1e-3; % relative to array face
assert(norm(target-[0 0 20e-3])<0.5e-3,'iceind:CuringFieldTarget', ...
    'Exported focus is not the assumed 20 mm on-axis target.');
activeX=sort(positions(active,1));
span=max(activeX)-min(activeX)+width;
perElementProxy=area*kg.dt*sum(double(wave(active,:)).^2,2);
totalProxy=sum(perElementProxy);
peakSamples=max(abs(double(wave(active,:))),[],2);
fftLength=2^nextpow2(size(wave,2)*4);
spec=abs(fft(double(wave(active(1),:)),fftLength)).^2;
freq=(0:fftLength/2)/(fftLength*kg.dt); spec=spec(1:numel(freq));
m=struct('case_tag',c.tag,'variant',c.variant,'driver_mat',driverMat, ...
    'driver_sha256',iceind.curing_field_sha256(driverMat), ...
    'num_active',numel(active), ...
    'source_geometry_provenance','existing_code_unverified', ...
    'medium_provenance',c.provenance, ...
    'pml_cells',pml,'dx_m',c.dx_m, ...
    'source_z_offset_m',c.source_offset_m, ...
    'source_z_kgrid_m',sourceZ,'dt_s',kg.dt,'Nt',kg.Nt,'t_end_s',kg.t_array(end), ...
    'minimum_end_time_s',c.minimum_end_time_s,'wave_end_s',waveEnd, ...
    'one_way_bound_s',distance/b.sound_speed_m_s, ...
    'time_window_definition',['Nt*dt with Nt=max(kg.Nt,ceil(minimum_end_time_s/dt)+1); ' ...
        'includes one-way aperture-to-far-corner bound and a 1 us margin'], ...
    'element_width_m',width,'element_height_m',height,'element_area_m2',area, ...
    'active_area_m2',area*numel(active),'area_error_m2',areaError, ...
    'active_pitch_m',median(diff(activeX)),'active_center_x_m',mean(activeX), ...
    'aperture_span_m',span,'fill_fraction_of_span',area*numel(active)/(span*height), ...
    'f_number_target_over_span',target(3)/span, ...
    'active_center_arrival_spread_s',max(q.delay_s(active)'+ ...
        vecnorm(positions(active,:)-target,2,2)/b.sound_speed_m_s)-min(q.delay_s(active)'+ ...
        vecnorm(positions(active,:)-target,2,2)/b.sound_speed_m_s), ...
    'waveform',wm,'source_amplitude_definition','assumed 1 Pa reference per element; not voltage calibrated', ...
    'source_proxy_total_pa2_s_m2',totalProxy, ...
    'source_proxy_definition',['sum_e element_area*dt*sum_t(s_e(t)^2); ' ...
        'Pa^2 s m^2; not acoustic power or energy'], ...
    'per_element_peak_sample_spread_relative',(max(peakSamples)-min(peakSamples))/mean(peakSamples), ...
    'equal_signal_scale_across_elements',true, ...
    'spectral_energy_above_spatial_nyquist_fraction', ...
        sum(spec(freq>b.sound_speed_m_s/(2*c.dx_m)))/sum(spec), ...
    'points_per_wavelength',b.sound_speed_m_s/(q.frequency_hz*c.dx_m), ...
    'source_model','assumed_equal_per_element_flat_rectangular_additive_pressure_no_lens', ...
    'solver','kspaceFirstOrder3D','solver_device','cpu');
m.source_ranks=ranks;
m.grid_size=n;
m.grid_with_pml=n+2*pml;
m.domain_m=c.domain_m;
m.foci_mm=target*1e3;
m.target_m=[0 0 20]*1e-3;
m.per_element_proxy_pa2_s_m2=perElementProxy;
end
