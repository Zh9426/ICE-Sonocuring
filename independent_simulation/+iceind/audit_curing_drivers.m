fclose(fid);
end

function [starts,counts,unknown] = rebuild_timeline(Event,SeqControl)
%REBUILD_TIMELINE Reconstruct scheduled starts from Event/SeqControl only.
% TTNA arguments are microseconds; noop arguments are 200 ns ticks.
starts = zeros(1,numel(Event));
counts = struct('timeToNextAcq',0,'noop',0,'setTPCProfile',0,'stop',0,'other',0);
unknown = {};
t = 0;
for e = 1:numel(Event)
    starts(e) = t;
    ids = Event(e).seqControl;
    ids = ids(ids>0);
    for j = 1:numel(ids)
        sc = SeqControl(ids(j));
        switch sc.command
            case 'timeToNextAcq'
                counts.timeToNextAcq = counts.timeToNextAcq + 1;
                t = t + sc.argument;
            case 'noop'
                counts.noop = counts.noop + 1;
                t = t + sc.argument/5;
            case 'setTPCProfile'
                counts.setTPCProfile = counts.setTPCProfile + 1;
            case 'stop'
                counts.stop = counts.stop + 1;
            otherwise
                counts.other = counts.other + 1;
                unknown{end+1} = sc.command;
        end
    end
end
end

function text = cmdForEvent(S,idx)
ids = S.Event(idx).seqControl;
ids = ids(ids>0);
if isempty(ids)
    text = '';
else
    text = strjoin({S.SeqControl(ids).command},'|');
end
end

function c = mkcheck(variant,name,expected,actual,pass,note)
c = struct('variant',variant,'check',name,'expected',brief(expected), ...
    'actual',brief(actual),'pass',logical(pass),'note',note);
end

function s = brief(v)
if ischar(v)
    s = v;
elseif isstring(v)
    s = strjoin(cellstr(v),' | ');
elseif islogical(v) && isscalar(v)
    s = mat2str(v);
elseif isnumeric(v) && isscalar(v)
    if isfinite(v)
        s = sprintf('%.12g',double(v));
    else
        s = num2str(v);
    end
elseif isnumeric(v) || islogical(v)
    s = mat2str(double(v),10);
elseif iscell(v)
    if isempty(v)
        s = '';
    else
        parts = cellfun(@brief,v,'UniformOutput',false);
        s = strjoin(parts,' | ');
    end
else
    try
        s = jsonencode(v);
    catch
        s = '<unprintable>';
    end
end
end

function h = sha256File(path)
h = 'unavailable';
try
    fid = fopen(path,'rb');
    if fid < 0
        return
    end
    bytes = fread(fid,Inf,'*uint8');
    fclose(fid);
    md = java.security.MessageDigest.getInstance('SHA-256');
    md.update(typecast(bytes,'int8'));
    digest = typecast(md.digest(),'uint8');
    h = lower(reshape(dec2hex(digest,2)',1,[]));
catch
    h = 'unavailable';
end
end
