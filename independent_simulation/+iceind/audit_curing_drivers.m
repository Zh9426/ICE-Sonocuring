function summary = audit_curing_drivers(outroot)
%AUDIT_CURING_DRIVERS Fresh-export + MAT-readback audit of the four TX-only drivers.
%   Calls SetUpICE_Curing_All64 / Center48 / Center32 / Center16 with an explicit
%   fresh output directory, reloads every saved MAT, and compares the loaded
%   object values against source-derived expectations.
%
%   This function only builds and saves offline MATLAB objects. It does not
%   call VSX, activate a system, load a sequence, or touch hardware. Driver
%   parameters remain existing_code_unverified / assumed; no value here is a
%   measured acoustic output, thermal result, or curing endpoint.
%
%   Usage (from independent_simulation):
%       summary = iceind.audit_curing_drivers();            % timestamped dir
%       summary = iceind.audit_curing_drivers(outroot);     % explicit empty dir
%
%   The function refuses to write into a non-empty output directory.

if nargin < 1
    outroot = '';
end
thisFile = mfilename('fullpath');
indepRoot = fileparts(fileparts(thisFile));
repoRoot = fileparts(indepRoot);
if isempty(outroot)
    outroot = fullfile(indepRoot,'results', ...
        ['curing_driver_audit_' datestr(now,'yyyymmdd_HHMMSS')]);
end
outroot = char(outroot);
if isfolder(outroot)
    entries = dir(outroot);
    entryNames = {entries.name};
    entryNames = entryNames(~ismember(entryNames,{'.','..'}));
    if ~isempty(entryNames)
        error('iceind:Audit','Refusing to write into non-empty output directory: %s',outroot);
    end
else
    mkdir(outroot);
end
driversDir = fullfile(outroot,'drivers');
if ~isfolder(driversDir), mkdir(driversDir); end

dualDir = fullfile(repoRoot,'verasonics','dual_mode');
curingDir = fullfile(repoRoot,'verasonics','curing_mode');
if ~isfolder(dualDir) || ~isfolder(curingDir)
    error('iceind:Audit','Driver directories not found under %s.',repoRoot);
end
addpath(dualDir);
addpath(curingDir);

% Hard-coded task targets, independent of the config/report under test.
% These come from the task statement and README, not from the built objects.
numElements = 64;
cMmUs = 1.54;
pitchMm = 0.13;
elementWidthMm = 0.11;
xTargetMm = ((1:numElements)-32.5)*pitchMm;
focusTargetMm = [0 0 20];
twFrequencyMhz = 6;
twCycles = 20;
twHalfCycles = 40;
twActiveFraction = 0.67;
twPolarity = 1;
burstTargetUs = twCycles/twFrequencyMhz;
expectedGroups = 30;
expectedPulses = 10;
expectedFoci = 1;
expectedPriUs = 1000;
expectedRechargeUs = 10000;
expectedInitialSettleUs = 5000;
expectedGuardUs = 5;
expectedTtna = expectedGroups*expectedFoci*(expectedPulses-1);
expectedNoops = 1 + expectedGroups*expectedFoci*2;
expectedTx = expectedGroups*expectedFoci*expectedPulses;
expectedEvents = 2 + expectedGroups*expectedFoci*(expectedPulses+2) + 1;
expectedSeqControl = expectedTtna + expectedNoops + 2;
expectedPulsesPerElement = expectedGroups*expectedFoci*expectedPulses;

variants = struct( ...
    'name', {'All64','Center48','Center32','Center16'}, ...
    'entry', {'SetUpICE_Curing_All64','SetUpICE_Curing_Center48', ...
              'SetUpICE_Curing_Center32','SetUpICE_Curing_Center16'}, ...
    'ranks', {1:64, 9:56, 17:48, 25:40});
expectedAperture = [8.30 6.22 4.14 2.06];

expRows = struct('variant',{},'ranks',{},'count',{},'aperture_mm',{}, ...
    'focus_xyz_mm',{},'tw_frequency_mhz',{},'tw_half_cycles',{},'burst_us',{}, ...
    'expected_arrival_us',{},'expected_max_delay_us',{},'events',{}, ...
    'tx_events',{},'ttna_commands',{},'noop_commands',{},'seqcontrol',{}, ...
    'pulses_total',{},'per_element_pulses',{},'per_element_on_time_us',{}, ...
    'min_tx_interval_us',{});
for k = 1:numel(variants)
    rk = variants(k).ranks;
    xa = xTargetMm(rk);
    dist = sqrt((xa-focusTargetMm(1)).^2 + (0-focusTargetMm(2)).^2 + ...
        focusTargetMm(3)^2);
    expRows(end+1) = struct('variant',variants(k).name, ...
        'ranks',sprintf('%d:%d',min(rk),max(rk)),'count',numel(rk), ...
        'aperture_mm',max(xa)-min(xa)+elementWidthMm, ...
        'focus_xyz_mm',mat2str(focusTargetMm,6), ...
        'tw_frequency_mhz',twFrequencyMhz, ...
        'tw_half_cycles',twHalfCycles,'burst_us',burstTargetUs, ...
        'expected_arrival_us',max(dist)/cMmUs, ...
        'expected_max_delay_us',(max(dist)-min(dist))/cMmUs, ...
        'events',expectedEvents,'tx_events',expectedTx, ...
        'ttna_commands',expectedTtna,'noop_commands',expectedNoops, ...
        'seqcontrol',expectedSeqControl, ...
        'pulses_total',expectedPulsesPerElement, ...
        'per_element_pulses',expectedPulsesPerElement, ...
        'per_element_on_time_us',expectedPulsesPerElement*burstTargetUs, ...
        'min_tx_interval_us',expectedPriUs);
end
writetable(struct2table(expRows),fullfile(outroot,'expected_values.csv'),'Encoding','UTF-8');

checks = struct('variant',{},'check',{},'expected',{},'actual',{},'pass',{},'note',{});
rows = struct('variant',{},'entry',{},'mat_path',{},'mat_bytes',{},'mat_sha256',{}, ...
    'selected_count',{},'first_rank',{},'last_rank',{},'aperture_mm',{}, ...
    'center_x_mm',{},'focus_xyz_mm',{},'tw_frequency_mhz',{},'tw_cycles',{}, ...
    'tw_half_cycles',{},'burst_us',{},'max_delay_us',{},'arrival_us',{}, ...
    'arrival_spread_us',{},'events',{},'tx_events',{},'ttna_commands',{}, ...
    'noop_commands',{},'receive_objects',{},'dma_commands',{},'pulses_total',{}, ...
    'pulses_per_element',{},'nominal_group_on_us',{},'nominal_total_on_us',{}, ...
    'total_element_on_time_us',{},'min_tx_interval_us',{}, ...
    'element_min_interval_us',{},'stop_ok',{},'tpc_xmit_duration_us',{}, ...
    'tpc_hv_omitted',{},'simulate_mode',{},'reconstructed_end_us',{}, ...
    'reported_end_us',{},'report_event_rows',{});
delayRows = struct('variant',{},'logical_element',{},'physical_rank',{},'x_mm',{}, ...
    'active',{},'delay_wls',{},'delay_us',{},'distance_mm',{},'arrival_us',{});
eventRows = struct('variant',{},'event_index',{},'kind',{},'tx',{},'rcv',{}, ...
    'recon',{},'process',{},'seq_control_command',{},'scheduled_start_us',{}, ...
    'reported_start_us',{});

fprintf('AUDIT outdir: %s\n',outroot);
fprintf('AUDIT MATLAB: %s\n',version);

for k = 1:numel(variants)
    vname = variants(k).name;
    ranks = variants(k).ranks(:)';
    nActive = numel(ranks);
    before = dir(fullfile(driversDir,'*.mat'));
    try
        [seq,report,cfg] = feval(variants(k).entry,[],driversDir);
    catch err
        checks(end+1) = mkcheck(vname,'entry_build','success',err.message,false,err.identifier);
        fprintf('AUDIT %s: entry failed: %s\n',vname,err.message);
        continue
    end
    try
    after = dir(fullfile(driversDir,'*.mat'));
    newNames = setdiff({after.name},{before.name});

    mp = char(report.output_paths.mat);
    [~,matStem,matExt] = fileparts(mp);
    expectedMatName = [matStem matExt];

    checks(end+1) = mkcheck(vname,'entry_ranks',ranks,cfg.partition.exposure_ranks, ...
        isequal(cfg.partition.exposure_ranks,ranks),'Entry must select its documented ranks.');
    checks(end+1) = mkcheck(vname,'fresh_export',{expectedMatName},newNames, ...
        numel(newNames)==1 && strcmp(newNames{1},expectedMatName), ...
        'Exactly one new MAT must appear; no historical file may be overwritten.');
    checks(end+1) = mkcheck(vname,'export_location',driversDir,mp, ...
        startsWith(mp,[driversDir filesep]) && ~contains(mp,fullfile('results','curing_only_2026-11-03')), ...
        'Export must be under the fresh audit directory.');
    checks(end+1) = mkcheck(vname,'mat_exists',true,isfile(mp),isfile(mp),'');

    if ~isfile(mp)
        error('iceind:Audit','MAT file was not created: %s',mp);
    end
    matInfo = dir(mp);
    h = sha256File(mp);
    checks(end+1) = mkcheck(vname,'mat_sha256',64,numel(h),numel(h)==64, ...
        'SHA-256 of the saved MAT (recorded for provenance).');

    S = load(mp);
    required = {'Trans','Resource','TW','TX','TPC','Event','SeqControl','ICEConfig','ICEReport'};
    missing = required(~isfield(S,required));
    checks(end+1) = mkcheck(vname,'mat_payload_fields',required,missing,isempty(missing), ...
        'Minimal payload plus embedded config/report.');
    if ~isempty(missing)
        error('iceind:Audit','MAT payload is missing required fields.');
    end
    C = S.ICEConfig;
    R = S.ICEReport;

    seqFields = {'Trans','Resource','TW','TX','TPC','Event','SeqControl'};
    sameSeq = true;
    for f = 1:numel(seqFields)
        sameSeq = sameSeq && isequaln(S.(seqFields{f}),seq.(seqFields{f}));
    end
    checks(end+1) = mkcheck(vname,'mat_roundtrip_sequence',true,sameSeq,sameSeq, ...
        'Loaded sequence objects must equal the returned objects.');
    checks(end+1) = mkcheck(vname,'mat_roundtrip_config',true,isequaln(C,cfg), ...
        isequaln(C,cfg),'Embedded config must equal the returned config.');
    checks(end+1) = mkcheck(vname,'mat_roundtrip_report',true, ...
        isequaln(R,rmfield(report,'output_paths')), ...
        isequaln(R,rmfield(report,'output_paths')), ...
        'Embedded report must equal the returned report before output paths were attached.');

    lambdaMm = S.Resource.Parameters.speedOfSound/1000/S.Trans.frequency;
    xmm = S.Trans.ElementPos(:,1)*lambdaMm;
    maskExp = ismember(1:64,ranks);
    active = find(S.TX(1).Apod(:) > 0);
    nActiveLoaded = numel(active);

    badFields = intersect(fieldnames(S), ...
        {'Receive','PData','Recon','Process','TGC','UI','Media','P'});
    checks(end+1) = mkcheck(vname,'no_receive_objects',{},badFields,isempty(badFields), ...
        'No Receive/PData/Recon/Process/TGC/UI/Media objects in the MAT.');
    checks(end+1) = mkcheck(vname,'resource_only_parameters',{'Parameters'}, ...
        fieldnames(S.Resource),isequal(fieldnames(S.Resource),{'Parameters'}),'');

    cmds = {S.SeqControl.command};
    dmaNames = {'transferToHost','returnToMatlab','jump','reconstruct'};
    dmaFound = cmds(ismember(cmds,dmaNames));
    checks(end+1) = mkcheck(vname,'no_dma_or_return_commands',{},dmaFound, ...
        isempty(dmaFound),'No DMA/reconstruct/return/jump sequence controls.');

    P = S.Resource.Parameters;
    resourceCore = [P.numTransmit P.numRcvChannels P.simulateMode P.freezeOnStart ...
        P.startEvent P.speedOfSound];
    checks(end+1) = mkcheck(vname,'resource_core',[128 128 1 1 1 1540],resourceCore, ...
        isequal(resourceCore,[128 128 1 1 1 1540]), ...
        'Two 64-channel connectors, offline simulateMode, start at event 1, 1540 m/s.');
    probeCore = [S.Trans.numelements S.Trans.frequency S.Trans.spacingMm, ...
        S.Trans.elementWidth*lambdaMm S.Trans.connType S.Trans.id];
    checks(end+1) = mkcheck(vname,'probe_geometry', ...
        [64 6.5 0.13 0.11 4 -1],probeCore, ...
        max(abs(probeCore-[64 6.5 0.13 0.11 4 -1]))<1e-9, ...
        'Source-derived probe values, not manufacturer calibration.');
    checks(end+1) = mkcheck(vname,'connector_mapping',1:64,S.Trans.ConnectorES(:)', ...
        isequal(S.Trans.ConnectorES(:)',1:64),'ConnectorES executes as 1:64.');

    [~,ord] = sort(xmm);
    checks(end+1) = mkcheck(vname,'physical_x_ascending',1:64,ord(:)', ...
        isequal(ord(:)',1:64),'ElementPos x must increase with logical element index.');
    posErr = max(abs(xmm(:)'-xTargetMm));
    checks(end+1) = mkcheck(vname,'element_positions_mm',0,posErr,posErr<1e-9, ...
        '64 hard-coded positions x=((1:64)-32.5)*0.13 mm.');
    planeErr = max(abs([S.Trans.ElementPos(:,2); S.Trans.ElementPos(:,3)]));
    checks(end+1) = mkcheck(vname,'element_plane_yz',0,planeErr,planeErr<1e-12,'');
    [~,~,colRef] = unique(xmm);
    checks(end+1) = mkcheck(vname,'partition_rank_by_x',colRef(:)',R.partition.column(:)', ...
        isequal(R.partition.column(:)',colRef(:)'), ...
        'Reported physical rank must be the ascending-x rank.');
    expApod = double(maskExp);
    checks(end+1) = mkcheck(vname,'tx_apod_mask',expApod,S.TX(1).Apod(:)', ...
        isequal(double(S.TX(1).Apod(:)'),expApod), ...
        'Actual TX.Apod must equal the hard-coded physical-rank mask.');
    checks(end+1) = mkcheck(vname,'exposure_rank_mask',ranks,active(:)', ...
        isequal(active(:)',ranks),'Active apodization must match the requested physical ranks.');
    checks(end+1) = mkcheck(vname,'exposure_mask_matches_ranks',true, ...
        isequal(double(R.partition.exposure_mask(:)'),double(maskExp)), ...
        isequal(double(R.partition.exposure_mask(:)'),double(maskExp)),'');

    actualWidthMm = S.Trans.elementWidth*lambdaMm;
    apMeas = max(xmm(active))-min(xmm(active)) + actualWidthMm;
    apExp = max(xTargetMm(ranks))-min(xTargetMm(ranks)) + elementWidthMm;
    checks(end+1) = mkcheck(vname,'aperture_mm',apExp,apMeas,abs(apMeas-apExp)<1e-9, ...
        'Hard-coded edge span plus 0.11 mm element width.');
    checks(end+1) = mkcheck(vname,'aperture_matches_expected',expectedAperture(k),apMeas, ...
        abs(apMeas-expectedAperture(k))<1e-9,'README-published target.');
    checks(end+1) = mkcheck(vname,'aperture_center_mm',0,mean(xmm(active)), ...
        abs(mean(xmm(active)))<1e-12,'Subsets are centered on x=0.');
    checks(end+1) = mkcheck(vname,'report_aperture_agrees',apMeas, ...
        R.operating_envelope.exposure_aperture_width_mm, ...
        abs(R.operating_envelope.exposure_aperture_width_mm-apMeas)<1e-9, ...
        'Report cross-check after the max-min aperture fix.');

    checks(end+1) = mkcheck(vname,'tw_single_parametric',true, ...
        isscalar(S.TW) && strcmp(S.TW(1).type,'parametric'), ...
        isscalar(S.TW) && strcmp(S.TW(1).type,'parametric'),'Exactly one transmit waveform.');
    twp = S.TW(1).Parameters;
    checks(end+1) = mkcheck(vname,'tw_frequency_mhz',twFrequencyMhz,twp(1), ...
        abs(twp(1)-twFrequencyMhz)<1e-12,'');
    checks(end+1) = mkcheck(vname,'tw_half_cycles',twHalfCycles,twp(3), ...
        abs(twp(3)-twHalfCycles)<1e-12,'40 half-cycles = 20 full cycles at 6 MHz.');
    checks(end+1) = mkcheck(vname,'tw_cycles',twCycles,twp(3)/2, ...
        abs(twp(3)/2-twCycles)<1e-12,'');
    checks(end+1) = mkcheck(vname,'tw_active_fraction',twActiveFraction,twp(2), ...
        abs(twp(2)-twActiveFraction)<1e-12,'');
    checks(end+1) = mkcheck(vname,'tw_polarity',twPolarity,twp(4), ...
        abs(twp(4)-twPolarity)<1e-12,'');
    burstActualUs = twp(3)/2/twp(1);
    checks(end+1) = mkcheck(vname,'burst_us',burstTargetUs, ...
        burstActualUs,abs(burstActualUs-burstTargetUs)<1e-12, ...
        'Nominal envelope duration, not a measured pulse.');

    fWls = S.TX(1).FocalPt;
    fMm = fWls*lambdaMm;
    origin = mean(S.Trans.ElementPos(active,1:3),1);
    originTargetWls = [mean(xTargetMm(ranks)) 0 0];
    focusTargetWls = focusTargetMm/lambdaMm;
    checks(end+1) = mkcheck(vname,'tx_count',expectedFoci,numel(S.TX), ...
        numel(S.TX)==expectedFoci,'One TX per configured focus.');
    checks(end+1) = mkcheck(vname,'focal_point_mm',focusTargetMm,fMm, ...
        max(abs(fMm-focusTargetMm))<1e-9,'Actual TX.FocalPt converted back to mm.');
    checks(end+1) = mkcheck(vname,'focal_point_wls',focusTargetWls,fWls, ...
        max(abs(fWls-focusTargetWls))<1e-12,'');
    checks(end+1) = mkcheck(vname,'focus_distance_wls', ...
        norm(focusTargetWls-originTargetWls),S.TX(1).focus, ...
        abs(S.TX(1).focus-norm(focusTargetWls-originTargetWls))<1e-12,'');
    checks(end+1) = mkcheck(vname,'steer_zero',0,S.TX(1).Steer(1), ...
        abs(S.TX(1).Steer(1))<1e-12,'Centered aperture, axial focus.');

    delayWls = S.TX(1).Delay(:);
    delayUs = delayWls/S.Trans.frequency;
    distWls = sqrt(sum((S.Trans.ElementPos(:,1:3)-fWls).^2,2));
    distMm = distWls*lambdaMm;
    arrivalUs = delayUs + distMm/cMmUs;
    delayActive = delayUs(active);

    checks(end+1) = mkcheck(vname,'inactive_delay_zero',true, ...
        all(delayWls(~maskExp(:))==0),all(delayWls(~maskExp(:))==0), ...
        'Unselected elements must carry zero delay and zero apodization.');
    symErr = max(abs(delayActive-flipud(delayActive)));
    checks(end+1) = mkcheck(vname,'delay_symmetry_us',0,symErr,symErr<1e-12, ...
        'Mirror elements around x=0 must have equal delays.');
    half = nActive/2;
    monoOk = all(diff(delayActive(1:half))>=-1e-12) && ...
        all(diff(delayActive(half+1:end))<=1e-12);
    [~,imax] = max(delayActive);
    edgeOk = abs(delayActive(1))<1e-9 && abs(delayActive(end))<1e-9;
    checks(end+1) = mkcheck(vname,'delay_profile_v',true,monoOk && edgeOk && ...
        ismember(imax,[half half+1]),monoOk && edgeOk && ismember(imax,[half half+1]), ...
        'Zero at both edges, maximum at the two center elements.');
    checks(end+1) = mkcheck(vname,'delay_within_45p5us',true, ...
        max(delayUs)<=45.5,max(delayUs)<=45.5,'D00163 TX.Delay software check.');

    distTarget = sqrt((xTargetMm(ranks)'-focusTargetMm(1)).^2 + ...
        (0-focusTargetMm(2)).^2 + focusTargetMm(3)^2);
    expArrival = max(distTarget)/cMmUs;
    expMaxDelayUs = (max(distTarget)-min(distTarget))/cMmUs;
    arr = arrivalUs(active);
    spread = max(arr)-min(arr);
    checks(end+1) = mkcheck(vname,'focus_arrival_us',expArrival,mean(arr), ...
        abs(mean(arr)-expArrival)<1e-6,'Hard-coded target geometry; not cfg/report.');
    checks(end+1) = mkcheck(vname,'focus_arrival_spread_us',0,spread,spread<1e-9, ...
        'Equal-arrival check across active elements.');
    checks(end+1) = mkcheck(vname,'max_delay_us',expMaxDelayUs,max(delayUs), ...
        abs(max(delayUs)-expMaxDelayUs)<1e-6,'Hard-coded target geometry.');
    checks(end+1) = mkcheck(vname,'report_max_delay_agrees',max(delayUs), ...
        R.max_exposure_delay_us, ...
        abs(R.max_exposure_delay_us-max(delayUs))<1e-12,'Report cross-check only.');

    checks(end+1) = mkcheck(vname,'tpc_count',1,numel(S.TPC),isscalar(S.TPC),'');
    checks(end+1) = mkcheck(vname,'tpc_max_high_voltage',35,S.TPC(1).maxHighVoltage, ...
        S.TPC(1).maxHighVoltage==35,'Original source cap, not a burst rating.');
    checks(end+1) = mkcheck(vname,'tpc_xmit_duration_us',max(delayUs)+burstActualUs, ...
        S.TPC(1).xmitDuration, ...
        abs(S.TPC(1).xmitDuration-(max(delayUs)+burstActualUs))<1e-12,'');
    checks(end+1) = mkcheck(vname,'tpc_hv_omitted',true,~isfield(S.TPC,'hv'), ...
        ~isfield(S.TPC,'hv'),'Empty voltage request must not write TPC.hv.');
    checks(end+1) = mkcheck(vname,'report_hv_omitted_flag',true,R.startup_hv_omitted, ...
        R.startup_hv_omitted,'');

    info = {S.Event.info};
    kinds = cellfun(@(s) strtok(s),info,'UniformOutput',false);
    txIdxValues = [S.Event.tx];
    txMask = txIdxValues > 0;
    nTx = nnz(txMask);

    % --- Explicit object-index validation before any object is indexed. ---
    nTxObjects = numel(S.TX);
    nTwObjects = numel(S.TW);
    nScObjects = numel(S.SeqControl);
    nTpcObjects = numel(S.TPC);
    txTypeOk = isnumeric(txIdxValues) && isreal(txIdxValues) && ...
        all(isfinite(txIdxValues)) && all(txIdxValues==fix(txIdxValues));
    txIndexOk = txTypeOk && all(txIdxValues>=0 & txIdxValues<=nTxObjects);
    checks(end+1) = mkcheck(vname,'tx_index_bounds', ...
        sprintf('finite integers 0..%d',nTxObjects),unique(txIdxValues), ...
        txIndexOk,'Every Event.tx must be a finite integer in range.');
    scIdxValues = [];
    for e = 1:numel(S.Event)
        ids = S.Event(e).seqControl;
        scIdxValues = [scIdxValues ids(:)'];
    end
    if isempty(scIdxValues)
        scRange = [-1 -1];
    else
        scRange = [min(scIdxValues) max(scIdxValues)];
    end
    scTypeOk = isnumeric(scIdxValues) && isreal(scIdxValues) && ...
        all(isfinite(scIdxValues)) && all(scIdxValues==fix(scIdxValues));
    scIndexOk = scTypeOk && all(scIdxValues>=0 & scIdxValues<=nScObjects);
    checks(end+1) = mkcheck(vname,'seqcontrol_index_bounds', ...
        sprintf('finite integers 0..%d',nScObjects),scRange,scIndexOk, ...
        'Every Event.seqControl must be a finite integer in range.');
    wf = [S.TX.waveform];
    wfTypeOk = isnumeric(wf) && isreal(wf) && all(isfinite(wf)) && ...
        all(wf==fix(wf));
    wfOk = wfTypeOk && all(wf>=1 & wf<=nTwObjects);
    checks(end+1) = mkcheck(vname,'tx_waveform_index', ...
        sprintf('finite integers 1..%d',nTwObjects),unique(wf),wfOk, ...
        'Every TX.waveform must address an existing TW object.');
    profArgs = [];
    for i = 1:nScObjects
        if strcmp(S.SeqControl(i).command,'setTPCProfile')
            profArgs(end+1) = S.SeqControl(i).argument;
        end
    end
    if isempty(profArgs)
        profArgs = -1;
    end
    profOk = isnumeric(profArgs) && isreal(profArgs) && ...
        all(isfinite(profArgs)) && all(profArgs==fix(profArgs)) && ...
        all(profArgs>=1 & profArgs<=nTpcObjects);
    checks(end+1) = mkcheck(vname,'tpc_profile_index', ...
        sprintf('finite integers 1..%d',nTpcObjects),unique(profArgs),profOk, ...
        'setTPCProfile arguments must address an existing TPC entry.');
    checks(end+1) = mkcheck(vname,'tx_event_consistency',true, ...
        isequal(txMask,strcmp(kinds,'exposure_transmit')), ...
        isequal(txMask,strcmp(kinds,'exposure_transmit')), ...
        'Event.tx is positive exactly for exposure_transmit events.');
    checks(end+1) = mkcheck(vname,'single_exposure_tx_object',1, ...
        unique(txIdxValues(txMask)),isequal(unique(txIdxValues(txMask)),1), ...
        'All exposure events reference the configured focus TX.');

    % --- Rebuild timing from Event/SeqControl, not from the report. ---
    [reStarts,reCmd,reUnknown] = rebuild_timeline(S.Event,S.SeqControl);
    if numel(R.timing.event_rows)==numel(S.Event)
        reportStarts = [R.timing.event_rows.scheduled_start_lower_bound_us];
        reportRowsOk = true;
    else
        reportStarts = nan(1,numel(S.Event));
        reportRowsOk = false;
    end
    checks(end+1) = mkcheck(vname,'report_event_row_count',numel(S.Event), ...
        numel(R.timing.event_rows),reportRowsOk,'One report row per Event.');
    if reportRowsOk
        timelineErr = max(abs(reStarts-reportStarts));
    else
        timelineErr = NaN;
    end
    checks(end+1) = mkcheck(vname,'report_timeline_agrees',0,timelineErr, ...
        reportRowsOk && timelineErr<1e-9, ...
        'Reconstructed Event/SeqControl starts must match report timestamps.');

    txEventIdx = find(txMask);
    groupTtnaOk = numel(txEventIdx)==expectedTx;
    groupTtnaDetail = '';
    groupEndOk = groupTtnaOk;
    if groupTtnaOk
        for g = 1:expectedGroups
            idx = txEventIdx((g-1)*expectedPulses+(1:expectedPulses));
            args = [];
            for j = 1:numel(idx)
                ids = S.Event(idx(j)).seqControl;
                ids = ids(ids>0);
                for q = 1:numel(ids)
                    if strcmp(S.SeqControl(ids(q)).command,'timeToNextAcq')
                        args(end+1) = S.SeqControl(ids(q)).argument;
                    end
                end
            end
            if ~(numel(args)==expectedPulses-1 && all(args==expectedPriUs))
                groupTtnaOk = false;
                groupTtnaDetail = sprintf('group %d: %d TTNA, args %s', ...
                    g,numel(args),mat2str(args));
                break
            end
            if ~(strcmp(kinds{idx(end)+1},'exposure_complete') && ...
                    strcmp(kinds{idx(end)+2},'recharge'))
                groupEndOk = false;
                groupTtnaDetail = sprintf('group %d: completion/recharge order',g);
                break
            end
        end
    end
    checks(end+1) = mkcheck(vname,'per_group_nine_ttna_1000us',true, ...
        groupTtnaDetail,groupTtnaOk, ...
        'Each 10-pulse group must carry exactly nine 1000 us timeToNextAcq controls.');
    checks(end+1) = mkcheck(vname,'group_completion_order',true, ...
        groupEndOk,groupEndOk, ...
        'Each group ends with exposure_complete then recharge before the next group.');

    txStartsRe = reStarts(txMask);
    minIntRe = min(diff(txStartsRe));
    groupFirstStarts = reStarts(txEventIdx(1:expectedPulses:end));
    expEndActualUs = ceil((max(delayUs)+burstActualUs+expectedGuardUs)*5)/5;
    expCycleActualUs = (expectedPulses-1)*expectedPriUs + expEndActualUs + ...
        expectedRechargeUs;
    expTotalActualUs = expectedInitialSettleUs + expectedGroups*expCycleActualUs;
    groupStartErr = max(abs(groupFirstStarts - ...
        (expectedInitialSettleUs + (0:expectedGroups-1)*expCycleActualUs)));
    checks(end+1) = mkcheck(vname,'group_start_schedule_us',0,groupStartErr, ...
        groupStartErr<1e-9, ...
        'Group starts rebuilt from Event/SeqControl and actual delays.');

    checks(end+1) = mkcheck(vname,'event_total',expectedEvents,numel(S.Event), ...
        numel(S.Event)==expectedEvents,'2 initial + groups*(pulses+2) + stop.');
    checks(end+1) = mkcheck(vname,'tx_event_total',expectedTx,nTx,nTx==expectedTx, ...
        '30 groups x 1 focus x 10 pulses = 300.');
    checks(end+1) = mkcheck(vname,'event_rcv_zero',true, ...
        all([S.Event.rcv]==0),all([S.Event.rcv]==0),'No acquisition.');
    checks(end+1) = mkcheck(vname,'event_recon_process_zero',true, ...
        all([S.Event.recon]==0) && all([S.Event.process]==0), ...
        all([S.Event.recon]==0) && all([S.Event.process]==0),'No reconstruction/processing.');
    checks(end+1) = mkcheck(vname,'event_first_kinds', ...
        {'profile_switch','initial_settle'},kinds(1:2), ...
        isequal(kinds(1:2),{'profile_switch','initial_settle'}),'');
    checks(end+1) = mkcheck(vname,'event_last_stop','stop',kinds{end}, ...
        strcmp(kinds{end},'stop') && S.Event(end).tx==0 && S.Event(end).rcv==0, ...
        'Final event must freeze the finite sequence.');
    checks(end+1) = mkcheck(vname,'stop_command','stop',cmdForEvent(S,numel(S.Event)), ...
        strcmp(cmdForEvent(S,numel(S.Event)),'stop'),'');
    checks(end+1) = mkcheck(vname,'allowed_event_kinds', ...
        {'exposure_complete','exposure_transmit','initial_settle','profile_switch','recharge','stop'}, ...
        unique(kinds),isempty(setdiff(unique(kinds), ...
        {'exposure_complete','exposure_transmit','initial_settle','profile_switch','recharge','stop'})), ...
        'No imaging, recovery, or DMA event kinds.');

    checks(end+1) = mkcheck(vname,'ttna_count',expectedTtna,reCmd.timeToNextAcq, ...
        reCmd.timeToNextAcq==expectedTtna,'Counted from events, not report.');
    checks(end+1) = mkcheck(vname,'noop_count',expectedNoops,reCmd.noop, ...
        reCmd.noop==expectedNoops,'Counted from events, not report.');
    checks(end+1) = mkcheck(vname,'seqcontrol_total',expectedSeqControl,numel(S.SeqControl), ...
        numel(S.SeqControl)==expectedSeqControl,'');
    reMix = sprintf('setTPCProfile=%d; noop=%d; timeToNextAcq=%d; stop=%d', ...
        reCmd.setTPCProfile,reCmd.noop,reCmd.timeToNextAcq,reCmd.stop);
    cmdOk = reCmd.setTPCProfile==1 && reCmd.noop==expectedNoops && ...
        reCmd.timeToNextAcq==expectedTtna && reCmd.stop==1 && ...
        reCmd.other==0 && isempty(reUnknown);
    checks(end+1) = mkcheck(vname,'seqcontrol_command_mix', ...
        sprintf('setTPCProfile=1; noop=%d; timeToNextAcq=%d; stop=1', ...
        expectedNoops,expectedTtna),reMix,cmdOk, ...
        'Rebuilt from referenced Event.seqControl entries.');
    checks(end+1) = mkcheck(vname,'unknown_sequence_controls',{},reUnknown, ...
        isempty(reUnknown),'No unexpected sequence-control commands.');
    usedSc = unique(scIdxValues(scIdxValues>0));
    checks(end+1) = mkcheck(vname,'all_seqcontrols_referenced',nScObjects, ...
        numel(usedSc),numel(usedSc)==nScObjects && ...
        all(ismember(1:nScObjects,usedSc)), ...
        'Every SeqControl entry must be referenced by an event.');
    noopIdx = find(strcmp(cmds,'noop'));
    noopArgs = [S.SeqControl(noopIdx).argument];
    checks(end+1) = mkcheck(vname,'noop_argument_limit',true, ...
        isempty(noopArgs) || all(noopArgs>=1 & noopArgs<=2^25-1), ...
        isempty(noopArgs) || all(noopArgs>=1 & noopArgs<=2^25-1), ...
        'D00163 noop tick range.');

    checks(end+1) = mkcheck(vname,'timing_nominal_group_on_us', ...
        expectedPulses*burstTargetUs,R.timing.nominal_exposure_on_time_us, ...
        abs(R.timing.nominal_exposure_on_time_us-expectedPulses*burstTargetUs)<1e-9,'');
    checks(end+1) = mkcheck(vname,'timing_nominal_total_on_us', ...
        expectedPulsesPerElement*burstTargetUs,nTx*burstActualUs, ...
        abs(nTx*burstActualUs-expectedPulsesPerElement*burstTargetUs)<1e-9, ...
        'Reconstructed from TX-event count; 1 ms nominal envelope only.');
    checks(end+1) = mkcheck(vname,'report_total_on_time_agrees',nTx*burstActualUs, ...
        R.timing.nominal_total_exposure_on_time_us, ...
        abs(R.timing.nominal_total_exposure_on_time_us-nTx*burstActualUs)<1e-9,'');
    checks(end+1) = mkcheck(vname,'timing_total_pulses',expectedPulsesPerElement,nTx, ...
        nTx==expectedPulsesPerElement,'Counted from MAT events.');
    checks(end+1) = mkcheck(vname,'report_total_pulses_agrees',nTx, ...
        R.timing.total_exposure_pulses,R.timing.total_exposure_pulses==nTx,'');
    checks(end+1) = mkcheck(vname,'timing_no_imaging',0,R.timing.total_imaging_acquisitions, ...
        R.timing.total_imaging_acquisitions==0,'');
    checks(end+1) = mkcheck(vname,'timing_cycle_us',expCycleActualUs, ...
        R.timing.scheduled_cycle_us, ...
        abs(R.timing.scheduled_cycle_us-expCycleActualUs)<1e-9, ...
        '0.2 us noop quantization; actual MAT delays/burst.');
    checks(end+1) = mkcheck(vname,'timing_total_us',expTotalActualUs, ...
        R.timing.scheduled_total_us, ...
        abs(R.timing.scheduled_total_us-expTotalActualUs)<1e-9,'');
    checks(end+1) = mkcheck(vname,'timeline_total_us',expTotalActualUs,reStarts(end), ...
        abs(reStarts(end)-expTotalActualUs)<1e-9, ...
        'Stop start rebuilt from Event/SeqControl.');
    checks(end+1) = mkcheck(vname,'min_tx_interval_us',expectedPriUs,minIntRe, ...
        abs(minIntRe-expectedPriUs)<1e-9, ...
        'Reconstructed TX starts; shortest separation is the 1000 us PRI.');
    checks(end+1) = mkcheck(vname,'timing_no_receive_recovery',true, ...
        ~ismember('receive_recovery',unique(kinds)), ...
        ~ismember('receive_recovery',unique(kinds)),'Standalone TX-only omits it by design.');

    expPulsesVec = zeros(64,1); expPulsesVec(active) = expectedPulsesPerElement;
    expOnVec = zeros(64,1); expOnVec(active) = expectedPulsesPerElement*burstTargetUs;
    perElemCounts = zeros(64,1);
    perElemMinInt = nan(64,1);
    elementOrderOk = true;
    for el = 1:64
        times = [];
        for j = 1:numel(txEventIdx)
            e = txEventIdx(j);
            tx = S.Event(e).tx;
            if S.TX(tx).Apod(el)>0
                times(end+1) = reStarts(e) + ...
                    S.TX(tx).Delay(el)/S.Trans.frequency;
            end
        end
        perElemCounts(el) = numel(times);
        if numel(times)>=2
            dt = diff(times);
            if any(dt<=0)
                elementOrderOk = false;
            end
            perElemMinInt(el) = min(dt);
        end
    end
    perElemOnUs = perElemCounts*burstActualUs;
    checks(end+1) = mkcheck(vname,'per_element_pulses',expPulsesVec,perElemCounts, ...
        isequal(perElemCounts,expPulsesVec), ...
        'Reconstructed from MAT events/apodization; 300 active, 0 inactive.');
    checks(end+1) = mkcheck(vname,'per_element_on_time_us',expOnVec,perElemOnUs, ...
        max(abs(perElemOnUs-expOnVec))<1e-9, ...
        'Count x nominal burst; active 1 ms, inactive 0.');
    checks(end+1) = mkcheck(vname,'all_active_element_min_interval_us',expectedPriUs, ...
        perElemMinInt(active)',all(abs(perElemMinInt(active)-expectedPriUs)<1e-9), ...
        'Every active element, not only the maximum.');
    checks(end+1) = mkcheck(vname,'element_min_interval_us',expectedPriUs, ...
        max(perElemMinInt(active)), ...
        abs(max(perElemMinInt(active))-expectedPriUs)<1e-9,'');
    checks(end+1) = mkcheck(vname,'element_total_on_time_us', ...
        nActive*expectedPulsesPerElement*burstTargetUs,sum(perElemOnUs), ...
        abs(sum(perElemOnUs)-nActive*expectedPulsesPerElement*burstTargetUs)<1e-9,'');
    checks(end+1) = mkcheck(vname,'max_element_on_time_us', ...
        expectedPulsesPerElement*burstTargetUs,max(perElemOnUs), ...
        abs(max(perElemOnUs)-expectedPulsesPerElement*burstTargetUs)<1e-9,'');
    checks(end+1) = mkcheck(vname,'element_order_positive',true,elementOrderOk, ...
        elementOrderOk,'Per-element transmit times strictly increase.');
    checks(end+1) = mkcheck(vname,'local_duty',burstTargetUs/expectedPriUs, ...
        max(burstActualUs./perElemMinInt(active)), ...
        abs(max(burstActualUs./perElemMinInt(active))- ...
        burstTargetUs/expectedPriUs)<1e-12, ...
        'Nominal burst/PRI, not acoustic duty.');

    pe = R.operating_envelope.per_element;
    reportPeOk = isequal(pe.exposure_pulses(:),perElemCounts) && ...
        max(abs(pe.exposure_on_time_us(:)-perElemOnUs))<1e-9;
    if all(isfinite(perElemMinInt(active))) && ...
            all(isfinite(pe.minimum_start_interval_us(active)))
        reportPeOk = reportPeOk && ...
            max(abs(pe.minimum_start_interval_us(active)-perElemMinInt(active)))<1e-9;
    else
        reportPeOk = false;
    end
    checks(end+1) = mkcheck(vname,'report_per_element_agrees',true,reportPeOk, ...
        reportPeOk,'Report is cross-checked, never the primary source.');

    checks(end+1) = mkcheck(vname,'report_mode','exposure_only',R.mode, ...
        strcmp(R.mode,'exposure_only'),'');
    checks(end+1) = mkcheck(vname,'report_no_hardware_run',false,R.hardware_run, ...
        R.hardware_run==false,'Offline build only.');
    checks(end+1) = mkcheck(vname,'report_vsx','not_run',R.vsx_validation, ...
        strcmp(R.vsx_validation,'not_run'),'VSX was not invoked.');
    checks(end+1) = mkcheck(vname,'report_physical','unknown',R.physical_validation, ...
        strcmp(R.physical_validation,'unknown'),'No physical validation.');
    checks(end+1) = mkcheck(vname,'report_num_imaging_angles',0,R.num_imaging_angles, ...
        R.num_imaging_angles==0,'');
    checks(end+1) = mkcheck(vname,'config_exposure_frequency',twFrequencyMhz, ...
        C.exposure.frequency_mhz,abs(C.exposure.frequency_mhz-twFrequencyMhz)<1e-12,'');
    checks(end+1) = mkcheck(vname,'config_exposure_cycles',twCycles, ...
        C.exposure.cycles,C.exposure.cycles==twCycles,'');
    checks(end+1) = mkcheck(vname,'config_focus_target_mm',focusTargetMm, ...
        C.exposure.foci_mm(1,:),max(abs(C.exposure.foci_mm(1,:)-focusTargetMm))<1e-12,'');
    checks(end+1) = mkcheck(vname,'config_pri_us',expectedPriUs, ...
        C.exposure.pri_us,C.exposure.pri_us==expectedPriUs,'');
    checks(end+1) = mkcheck(vname,'config_pulses_per_focus',expectedPulses, ...
        C.exposure.pulses_per_focus,C.exposure.pulses_per_focus==expectedPulses,'');
    checks(end+1) = mkcheck(vname,'config_voltage_empty',true, ...
        isempty(C.exposure.voltage_v),isempty(C.exposure.voltage_v), ...
        'No explicit TPC.hv request.');
    checks(end+1) = mkcheck(vname,'imaging_aperture_zero',0, ...
        R.operating_envelope.imaging_aperture_width_mm, ...
        R.operating_envelope.imaging_aperture_width_mm==0, ...
        'Exercises the max-min empty-mask path in operating_envelope.');
    checks(end+1) = mkcheck(vname,'config_groups',expectedGroups,C.sequence.num_groups, ...
        C.sequence.num_groups==expectedGroups,'');
    checks(end+1) = mkcheck(vname,'config_no_imaging_field',true,~isfield(C,'imaging'), ...
        ~isfield(C,'imaging'),'');
    checks(end+1) = mkcheck(vname,'config_mode_and_layout', ...
        {'exposure_only','exposure_only_selected'}, ...
        {C.mode,C.partition.layout}, ...
        strcmp(C.mode,'exposure_only') && ...
        strcmp(C.partition.layout,'exposure_only_selected'),'');
    checks(end+1) = mkcheck(vname,'partition_no_imaging_role',[0 0], ...
        [R.partition.imaging_count R.partition.shared_count], ...
        R.partition.imaging_count==0 && R.partition.shared_count==0, ...
        'No element carries an imaging role in this standalone module.');
    checks(end+1) = mkcheck(vname,'config_no_receive_recovery',true, ...
        ~isfield(C.timing,'receive_recovery_us'),~isfield(C.timing,'receive_recovery_us'),'');
    checks(end+1) = mkcheck(vname,'finite_session_cap',true, ...
        nTx<=C.exposure.max_total_pulses,nTx<=C.exposure.max_total_pulses, ...
        'TX events counted from MAT, compared with the configured cap.');

    rows(end+1) = struct('variant',vname,'entry',variants(k).entry, ...
        'mat_path',mp,'mat_bytes',matInfo.bytes,'mat_sha256',h, ...
        'selected_count',nActiveLoaded,'first_rank',ranks(1),'last_rank',ranks(end), ...
        'aperture_mm',apMeas,'center_x_mm',mean(xmm(active)), ...
        'focus_xyz_mm',mat2str(fMm,6),'tw_frequency_mhz',twp(1), ...
        'tw_cycles',twp(3)/2,'tw_half_cycles',twp(3),'burst_us',burstActualUs, ...
        'max_delay_us',max(delayUs),'arrival_us',mean(arr), ...
        'arrival_spread_us',spread,'events',numel(S.Event),'tx_events',nTx, ...
        'ttna_commands',reCmd.timeToNextAcq,'noop_commands',reCmd.noop, ...
        'receive_objects',numel(badFields),'dma_commands',numel(dmaFound), ...
        'pulses_total',nTx,'pulses_per_element',max(perElemCounts), ...
        'nominal_group_on_us',R.timing.nominal_exposure_on_time_us, ...
        'nominal_total_on_us',nTx*burstActualUs, ...
        'total_element_on_time_us',sum(perElemOnUs), ...
        'min_tx_interval_us',minIntRe, ...
        'element_min_interval_us',max(perElemMinInt(active)), ...
        'stop_ok',strcmp(kinds{end},'stop'), ...
        'tpc_xmit_duration_us',S.TPC(1).xmitDuration, ...
        'tpc_hv_omitted',~isfield(S.TPC,'hv'), ...
        'simulate_mode',P.simulateMode,'reconstructed_end_us',reStarts(end), ...
        'reported_end_us',R.timing.scheduled_total_us, ...
        'report_event_rows',numel(R.timing.event_rows));

    for e = 1:numel(S.Event)
        eventRows(end+1) = struct('variant',vname,'event_index',e, ...
            'kind',kinds{e},'tx',S.Event(e).tx,'rcv',S.Event(e).rcv, ...
            'recon',S.Event(e).recon,'process',S.Event(e).process, ...
            'seq_control_command',cmdForEvent(S,e), ...
            'scheduled_start_us',reStarts(e), ...
            'reported_start_us',reportStarts(e));
