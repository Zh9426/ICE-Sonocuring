    for e = 1:64
        delayRows(end+1) = struct('variant',vname,'logical_element',e, ...
            'physical_rank',R.partition.column(e),'x_mm',xmm(e), ...
            'active',maskExp(e),'delay_wls',delayWls(e), ...
            'delay_us',delayUs(e),'distance_mm',distMm(e), ...
            'arrival_us',arrivalUs(e));
    end

    fprintf('AUDIT %s: events=%d tx=%d aperture=%.3f mm arrival=%.6f us\n', ...
        vname,numel(S.Event),nTx,apMeas,mean(arr));
    catch err
        checks(end+1) = mkcheck(vname,'analysis_error','success', ...
            err.message,false,err.identifier);
        fprintf('AUDIT %s: analysis failed: %s\n',vname,err.message);
    end
end

if isempty(rows)
    doneNames = {};
else
    doneNames = {rows.variant};
end
missingNames = setdiff({variants.name},doneNames);
checks(end+1) = mkcheck('ALL','four_variants_completed', ...
    {variants.name},missingNames,isempty(missingNames), ...
    'All four documented entry points must build and export.');

allPassed = ~isempty(checks) && all([checks.pass]);
checkTable = struct2table(checks);
writetable(checkTable,fullfile(outroot,'checks.csv'),'Encoding','UTF-8');
if ~isempty(rows)
    writetable(struct2table(rows),fullfile(outroot,'actual_values.csv'),'Encoding','UTF-8');
end
if ~isempty(delayRows)
    writetable(struct2table(delayRows),fullfile(outroot,'delay_table.csv'),'Encoding','UTF-8');
end
if ~isempty(eventRows)
    writetable(struct2table(eventRows),fullfile(outroot,'event_readback.csv'),'Encoding','UTF-8');
end

bad = checks(~[checks.pass]);
failed = struct('variant',{bad.variant},'check',{bad.check}, ...
    'expected',{bad.expected},'actual',{bad.actual},'note',{bad.note});
payload = struct('outdir',outroot,'matlab_version',version, ...
    'generated_at',datestr(now,31),'all_passed',allPassed, ...
    'checks_total',numel(checks),'checks_passed',numel(checks)-numel(bad), ...
    'checks_failed',numel(bad),'variants_completed',numel(rows));
if isempty(bad)
    payload.failed_checks = {};
else
    payload.failed_checks = failed;
end
fid = fopen(fullfile(outroot,'audit_summary.json'),'w','n','UTF-8');
if fid < 0
    error('iceind:Audit','Cannot write audit_summary.json under %s.',outroot);
end
fwrite(fid,unicode2native(jsonencode(payload,'PrettyPrint',true),'UTF-8'),'uint8');
fclose(fid);

writeReport(outroot,rows,checks,bad,repoRoot,allPassed);

summary = payload;
summary.failed_checks = failed;
summary.actual_values = rows;
fprintf('AUDIT total_checks=%d passed=%d failed=%d\n', ...
    numel(checks),numel(checks)-numel(bad),numel(bad));
end

