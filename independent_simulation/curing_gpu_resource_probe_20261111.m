function results=curing_gpu_resource_probe_20261111(variant,dx_um)
%CURING_GPU_RESOURCE_PROBE 16 steps on a real driver source; no field claim.
root=fileparts(mfilename('fullpath')); old=path; cleanup=onCleanup(@()path(old));
addpath(root,fullfile(root,'dependencies','k-wave-1.4.1','k-Wave'));
bin=fullfile(root,'dependencies','kwave-cuda-unified-v1.4.2');
assert(ismember(dx_um,[65 52]) && ismember(string(variant),["All64","Center16"]), ...
    'iceind:GPUResource','Only initial-stage variants/grids are supported.');
cases=iceind.curing_field_cases(); idx=find(strcmp({cases.variant},variant) & ...
    abs([cases.dx_m]-dx_um*1e-6)<1e-12,1); assert(~isempty(idx)); c=cases(idx);
drivers=struct('All64','ICE_CuringOnly_ExposureFFFFFFFFFFFFFFFF_exposure_only.mat', ...
    'Center16','ICE_CuringOnly_Exposure000000FFFF000000_exposure_only.mat');
driver=fullfile(root,'results','curing_export_2026-11-10',drivers.(variant));
out=fullfile(root,'results','curing_field_2026-11-10', ...
    sprintf('gpu_resource_%s_dx%d_20261111',lower(variant),dx_um));
assert(~isfolder(out),'iceind:NoOverwrite','Inspect existing GPU resource output.'); mkdir(out);
t=tic; [g,medium,source,sensor,meta]=iceind.curing_bli_prepare(c,driver); prepare_s=toc(t);
g.setTime(16,g.dt); source.p=source.p(:,1:16);
sensor.record={'p_max_all','p_min_all','p_rms','p_final'}; sensor.record_start_index=1;
t=tic; data=kspaceFirstOrder3DG(g,medium,source,sensor,'PMLInside',false, ...
    'PMLSize',meta.pml_cells,'PlotSim',false,'BinaryPath',bin, ...
    'BinaryName','kspaceFirstOrder-CUDA-windows.exe','DataPath',out, ...
    'DataName','resource','DeleteData',false,'DeviceNum',0,'VerboseLevel',1); elapsed=toc(t);
assert(numel(data.p_rms)==prod(meta.grid_size) && all(isfinite(data.p_rms),'all'), ...
    'iceind:GPUResource','Unexpected GPU RMS output.');
mode=h5read(fullfile(out,'resource_input.h5'),'/p_source_mode');
assert(mode==2,'iceind:GPUResource','Unexpected pressure source mode.');
results=struct('purpose','16-step GPU resource test; not a propagated field result', ...
    'variant',variant,'dx_um',dx_um,'grid',meta.grid_size,'steps',16,'dt_s',g.dt, ...
    'prepare_s',prepare_s,'elapsed_s',elapsed,'source_points',nnz(source.p_mask), ...
    'p_source_mode',double(mode),'matlab',version, ...
    'solver_release','community kspacefirstorder-unified v1.4.2; binary reports CUDA v1.3 build 3.6', ...
    'note','Inspect executable log for GPU device memory; no full-solve resource guarantee.');
iceind.curing_field_write_json(fullfile(out,'summary.json'),results); disp(results);
end
